-- Adicionar colunas jaApostouComSaldoReal e jaApostou à tabela Usuario
-- Este script verifica se as colunas já existem antes de adicionar

-- Verificar e adicionar jaApostouComSaldoReal
SET @dbname = DATABASE();
SET @tablename = 'Usuario';
SET @columnname = 'jaApostouComSaldoReal';
SET @preparedStatement = (SELECT IF(
  (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
    WHERE
      (table_name = @tablename)
      AND (table_schema = @dbname)
      AND (column_name = @columnname)
  ) > 0,
  'SELECT 1',
  CONCAT('ALTER TABLE ', @tablename, ' ADD COLUMN ', @columnname, ' BOOLEAN DEFAULT FALSE')
));
PREPARE alterIfNotExists FROM @preparedStatement;
EXECUTE alterIfNotExists;
DEALLOCATE PREPARE alterIfNotExists;

